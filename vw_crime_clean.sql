CREATE VIEW [dbo].[vw_crime_clean] AS
  WITH ranked AS (
    SELECT *,
           ROW_NUMBER() OVER (PARTITION BY CRIME_ID ORDER BY ID) AS rn
    FROM Crime_staging
    WHERE CRIME_ID IS NOT NULL
)
SELECT ID, CRIME_ID, [MONTH],REPORTED_BY, FALLS_WITHIN, [LOCATION],
LSOA_CODE, LSOA_NAME, CRIME_TYPE, LAST_OUTCOME_CAT
FROM ranked
WHERE rn = 1

UNION ALL

SELECT ID, CRIME_ID, [MONTH], REPORTED_BY, FALLS_WITHIN, [LOCATION],
       LSOA_CODE, LSOA_NAME, CRIME_TYPE, LAST_OUTCOME_CAT
FROM Crime_staging
WHERE CRIME_ID IS NULL;

GO


